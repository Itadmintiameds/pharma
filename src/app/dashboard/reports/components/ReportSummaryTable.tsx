import clsx from "clsx";
import { formatRupees } from "./reportUtils";

export interface SummaryLine {
  key: string;
  label: string;
  amount: number;
  /** A tinted line: a subtotal mid-table (Net Sales) or the closing total. */
  highlight?: boolean;
}

interface ReportSummaryTableProps {
  title: string;
  /** Lines under the title: "Period: …", "Pharmacy: …". */
  subtitles: string[];
  generatedOn: string;
  generatedBy: string;
  /** Column headings: the label column, then the amount column. */
  labelHeader: string;
  amountHeader: string;
  lines: SummaryLine[];
}

const CARD =
  "flex w-full flex-col gap-4 rounded-2xl bg-white p-4 shadow-[4px_4px_12px_0px_rgba(213,213,212,0.2),-4px_-4px_12px_0px_rgba(213,213,212,0.2),0px_0px_12px_0px_rgba(192,193,190,0.2)]";

/**
 * The results card of a summary report — one figure per line rather than a
 * list of records, so there is no record count and no paging, and the table
 * stays narrow instead of spanning the card.
 */
export default function ReportSummaryTable({
  title,
  subtitles,
  generatedOn,
  generatedBy,
  labelHeader,
  amountHeader,
  lines,
}: ReportSummaryTableProps) {
  return (
    <div className={CARD}>
      <div className="flex flex-wrap items-start gap-4">
        <div className="flex min-w-0 flex-1 flex-col gap-1">
          <h2 className="text-label-l5 font-semibold text-pneutral-900">{title}</h2>
          {subtitles.map((line) => (
            <p key={line} className="text-p3 text-pneutral-500">{line}</p>
          ))}
        </div>
        <div className="flex flex-col items-end gap-1 text-right text-p3 text-pneutral-500">
          <p>Generated on: {generatedOn}</p>
          <p>Generated by: {generatedBy}</p>
        </div>
      </div>

      <div className="w-180 max-w-full overflow-x-auto rounded-lg border border-pneutral-200">
        <table className="w-full border-collapse">
          <thead>
            <tr>
              <th className="h-14 w-[53%] border-r border-b border-pneutral-200 bg-secondary-600 px-3 py-2 text-left text-label-l3 font-semibold text-pneutral-50 uppercase">
                {labelHeader}
              </th>
              <th className="h-14 border-b border-pneutral-200 bg-secondary-600 px-3 py-2 text-right text-label-l3 font-semibold text-pneutral-50 uppercase">
                {amountHeader}
              </th>
            </tr>
          </thead>
          <tbody>
            {lines.map((line) => (
              <tr
                key={line.key}
                className={clsx(
                  "[&:last-child>td]:border-b-0",
                  line.highlight
                    ? "bg-primary-100 font-semibold text-primary-900"
                    : "bg-white text-pneutral-900",
                )}
              >
                <td className="h-13 border-r border-b border-pneutral-200 px-3 py-2 text-p3">
                  {line.label}
                </td>
                <td className="h-13 border-b border-pneutral-200 px-3 py-2 text-right text-p3 whitespace-nowrap">
                  {formatRupees(line.amount)}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
}
